export function listAceServices() {
  return ACE_SERVICE_CATALOG.map((service) => ({ ...service }));
}

export function getAceService(serviceId) {
  const service = ACE_SERVICE_CATALOG.find((candidate) => candidate.id === serviceId);
  if (!service) {
    const known = ACE_SERVICE_CATALOG.map((candidate) => candidate.id).join(', ');
    throw new Error(`unknown_ace_service:${serviceId}; known=${known}`);
  }
  return { ...service };
}

export function groupAceServicesByFamily() {
  const grouped = {};
  for (const service of ACE_SERVICE_CATALOG) {
    grouped[service.family] ??= [];
    grouped[service.family].push(service.id);
  }
  return grouped;
}

export function selectBountyCoreServices() {
  return [
    'openai-chat-completions',
    'serp-google-search',
    'flux-image-generation',
    'short-url',
  ].map(getAceService);
}
